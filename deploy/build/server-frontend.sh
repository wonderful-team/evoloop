#!/bin/bash
set -e

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
source "$SCRIPT_DIR/common.sh"

ENVIRONMENT="production"
VITE_API_URL=""
OUTPUT_DIR="dist"

while [[ $# -gt 0 ]]; do
  case $1 in
    --api-url) VITE_API_URL="$2"; shift 2 ;;
    --output) OUTPUT_DIR="$2"; shift 2 ;;
    --env) ENVIRONMENT="$2"; shift 2 ;;
    --dev) ENVIRONMENT="development"; shift ;;
    --help|-h)
      echo "Usage: $0 [options]"
      echo ""
      echo "Build frontend static assets for server deployment."
      echo ""
      echo "Options:"
      echo "  --api-url URL     Backend API URL (overrides .env)"
      echo "  --output DIR      Output directory (default: dist/)"
      echo "  --env ENV         Environment: development|production (default: production)"
      echo "  --dev             Shortcut for --env development"
      echo "  --help, -h        Show this help"
      exit 0
      ;;
    *) err "Unknown: $1"; exit 1 ;;
  esac
done

cd "$PROJECT_ROOT/frontend"

header "Building Frontend for Server Deployment ($ENVIRONMENT)"

# Vite will automatically read from the root .env generated by switch_env.sh
step "Installing dependencies"
if [ ! -d "node_modules" ]; then
  npm install
else
  ok "node_modules exists"
fi

if [ -z "$VITE_API_URL" ]; then
  VITE_API_URL=$(grep ^VITE_API_URL= .env | cut -d= -f2)
fi

step "Building frontend"
if [ "$OUTPUT_DIR" != "dist" ]; then
  VITE_API_URL="$VITE_API_URL" VITE_OUTPUT_DIR="$OUTPUT_DIR" npm run build
  if [ -d "dist" ]; then
    rm -rf "$OUTPUT_DIR"
    mv dist "$OUTPUT_DIR"
  fi
else
  VITE_API_URL="$VITE_API_URL" npm run build
fi

if [ -d "dist" ]; then
  ok "Frontend built ($ENVIRONMENT): $(du -sh dist | cut -f1)"
  info "Output: $PROJECT_ROOT/frontend/dist/"
else
  err "Build failed"
  exit 1
fi
